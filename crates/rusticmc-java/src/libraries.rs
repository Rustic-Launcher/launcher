//! Which libraries a version uses on this system: the classpath, the old-style natives to extract
//! (versions before 1.19 list a `natives` classifier per OS), and what to download for them.

use crate::download::FileDownload;
use crate::maven::{Coordinate, safe_relative};
use crate::platform::Platform;
use crate::rules::{Features, allowed};
use crate::version::{Artifact, Library, VersionJson};
use crate::{JavaError, Result};
use std::path::{Path, PathBuf};

/// A natives jar to unpack into the natives folder before a launch.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NativeJar {
    /// Relative to the game folder (`libraries/...`).
    pub path: PathBuf,
    /// Entry prefixes not to unpack (`META-INF/`).
    pub exclude: Vec<String>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct LibraryPlan {
    /// Relative to the game folder, in order.
    pub classpath: Vec<PathBuf>,
    pub natives: Vec<NativeJar>,
    /// What to fetch (files with a URL); the others must already be there (a loader installer
    /// wrote them).
    pub downloads: Vec<FileDownload>,
}

/// The plan of `version`'s libraries for `platform`. `libraries_host` serves libraries listed
/// with neither a download nor a repository (old files).
pub fn plan(
    version: &VersionJson,
    platform: &Platform,
    features: &Features,
    libraries_host: &str,
) -> Result<LibraryPlan> {
    let mut out = LibraryPlan::default();
    for lib in &version.libraries {
        if !allowed(&lib.rules, platform, features) {
            continue;
        }
        let native_classifier = lib
            .natives
            .as_ref()
            .and_then(|n| n.get(platform.os_name()))
            .map(|c| c.replace("${arch}", platform.bits()));
        // The main artifact: on the classpath (old natives-only entries have none).
        let main = lib.downloads.as_ref().and_then(|d| d.artifact.as_ref());
        let natives_only =
            lib.natives.is_some() && main.is_none() && lib.url.is_none() && lib.downloads.is_some();
        if !natives_only {
            if let Some(file) = artifact_file(lib, main, None, libraries_host)? {
                if !out.classpath.contains(&file.path) {
                    out.classpath.push(file.path.clone());
                }
                if !file.url.is_empty() {
                    out.downloads.push(file);
                }
            } else if lib.natives.is_none() {
                return Err(JavaError::bad(format!("library {}: no path", lib.name)));
            }
        }
        if let Some(classifier) = native_classifier {
            let artifact = lib
                .downloads
                .as_ref()
                .and_then(|d| d.classifiers.as_ref())
                .and_then(|c| c.get(&classifier));
            if let Some(file) = artifact_file(lib, artifact, Some(&classifier), libraries_host)? {
                out.natives.push(NativeJar {
                    path: file.path.clone(),
                    exclude: lib
                        .extract
                        .as_ref()
                        .map(|e| e.exclude.clone())
                        .unwrap_or_default(),
                });
                if !file.url.is_empty() {
                    out.downloads.push(file);
                }
            }
        }
    }
    out.downloads.sort_by(|a, b| a.path.cmp(&b.path));
    out.downloads.dedup_by(|a, b| a.path == b.path);
    Ok(out)
}

/// The file of a library (its main artifact, or a natives classifier): from `downloads` when
/// listed, else from its Maven coordinate on its repository (or Mojang's). An empty URL means "no
/// download" (generated by a loader installer). `None` when it has neither.
fn artifact_file(
    lib: &Library,
    artifact: Option<&Artifact>,
    classifier: Option<&str>,
    libraries_host: &str,
) -> Result<Option<FileDownload>> {
    let coordinate = Coordinate::parse(&lib.name).map(|mut c| {
        if let Some(cl) = classifier {
            c.classifier = Some(cl.to_owned());
        }
        c
    });
    if let Some(a) = artifact {
        let rel = match &a.path {
            Some(p) => p.clone(),
            None => coordinate
                .as_ref()
                .map(Coordinate::path)
                .ok_or_else(|| JavaError::bad(format!("library {}: bad name", lib.name)))?,
        };
        let path = Path::new("libraries").join(
            safe_relative(&rel)
                .ok_or_else(|| JavaError::bad(format!("library {}: unsafe path", lib.name)))?,
        );
        return Ok(Some(FileDownload {
            url: a.url.clone(),
            sha1: a.sha1.clone(),
            size: a.size,
            path,
        }));
    }
    // A classifier missing from `downloads.classifiers`: nothing for this OS.
    if classifier.is_some() && lib.downloads.is_some() {
        return Ok(None);
    }
    let Some(c) = coordinate else {
        return Err(JavaError::bad(format!("library {}: bad name", lib.name)));
    };
    let rel = c.path();
    let base = lib
        .url
        .as_deref()
        .filter(|u| !u.is_empty())
        .unwrap_or(libraries_host);
    Ok(Some(FileDownload {
        url: format!("{}/{rel}", base.trim_end_matches('/')),
        // The repository's checksum applies to the main artifact only.
        sha1: if classifier.is_none() {
            lib.sha1.clone()
        } else {
            None
        },
        size: if classifier.is_none() { lib.size } else { None },
        path: Path::new("libraries").join(rel),
    }))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::platform::{Arch, Os};
    use serde_json::json;

    fn win() -> Platform {
        Platform {
            os: Os::Windows,
            arch: Arch::X86_64,
            os_version: Some("10.0.26200".into()),
        }
    }

    fn mac() -> Platform {
        Platform {
            os: Os::Osx,
            arch: Arch::Arm64,
            os_version: None,
        }
    }

    const HOST: &str = "https://libraries.minecraft.net";

    /// Old-style natives (a 1.12-era shape, written for this test).
    fn legacy() -> VersionJson {
        serde_json::from_value(json!({"id": "old", "libraries": [
            {"name": "org.lwjgl.lwjgl:lwjgl:2.9.4", "rules": [{"action": "allow"}, {"action": "disallow", "os": {"name": "osx"}}],
             "downloads": {"artifact": {"path": "org/lwjgl/lwjgl/lwjgl/2.9.4/lwjgl-2.9.4.jar", "url": "https://libraries.minecraft.net/l.jar", "sha1": "1", "size": 1}}},
            {"name": "org.lwjgl.lwjgl:lwjgl-platform:2.9.4", "natives": {"linux": "natives-linux", "osx": "natives-osx", "windows": "natives-windows"},
             "extract": {"exclude": ["META-INF/"]},
             "downloads": {"classifiers": {
                "natives-windows": {"path": "org/lwjgl/lwjgl/lwjgl-platform/2.9.4/lwjgl-platform-2.9.4-natives-windows.jar", "url": "https://libraries.minecraft.net/w.jar", "sha1": "2", "size": 2},
                "natives-osx": {"path": "org/lwjgl/lwjgl/lwjgl-platform/2.9.4/lwjgl-platform-2.9.4-natives-osx.jar", "url": "https://libraries.minecraft.net/o.jar", "sha1": "3", "size": 3}
             }}},
            {"name": "tv.twitch:twitch-platform:5.16", "natives": {"windows": "natives-windows-${arch}"},
             "downloads": {"classifiers": {"natives-windows-64": {"path": "tv/twitch/twitch-platform/5.16/twitch-platform-5.16-natives-windows-64.jar", "url": "https://libraries.minecraft.net/t64.jar", "sha1": "4", "size": 4}}}},
            {"name": "com.mojang:text2speech:1.10.3", "natives": {"linux": "natives-linux", "windows": "natives-windows"},
             "downloads": {"artifact": {"path": "com/mojang/text2speech/1.10.3/text2speech-1.10.3.jar", "url": "https://libraries.minecraft.net/t.jar", "sha1": "5", "size": 5},
                           "classifiers": {"natives-windows": {"path": "com/mojang/text2speech/1.10.3/text2speech-1.10.3-natives-windows.jar", "url": "https://libraries.minecraft.net/tw.jar", "sha1": "6", "size": 6}}}}
        ]}))
        .unwrap()
    }

    #[test]
    fn legacy_natives_per_os_and_arch() {
        let p = plan(&legacy(), &win(), &Features::none(), HOST).unwrap();
        assert_eq!(
            p.classpath,
            vec![
                PathBuf::from("libraries/org/lwjgl/lwjgl/lwjgl/2.9.4/lwjgl-2.9.4.jar"),
                PathBuf::from("libraries/com/mojang/text2speech/1.10.3/text2speech-1.10.3.jar"),
            ]
        );
        let natives: Vec<_> = p.natives.iter().map(|n| n.path.clone()).collect();
        assert_eq!(natives.len(), 3);
        assert!(natives[1].ends_with("twitch-platform-5.16-natives-windows-64.jar"));
        assert_eq!(p.natives[0].exclude, vec!["META-INF/"]);
        assert_eq!(p.downloads.len(), 5);

        let m = plan(&legacy(), &mac(), &Features::none(), HOST).unwrap();
        // lwjgl is disallowed on macOS; text2speech has no macOS natives.
        assert_eq!(m.classpath.len(), 1);
        assert_eq!(m.natives.len(), 1);
        assert!(
            m.natives[0]
                .path
                .ends_with("lwjgl-platform-2.9.4-natives-osx.jar")
        );
    }

    #[test]
    fn maven_repository_libraries_and_installer_outputs() {
        let v: VersionJson = serde_json::from_value(json!({"id": "x", "libraries": [
            {"name": "net.fabricmc:fabric-loader:0.17.2", "url": "https://maven.fabricmc.net/", "sha1": "abc", "size": 10},
            {"name": "net.minecraftforge:forge:1.20.1-47.2.0:client", "downloads": {"artifact": {"path": "net/minecraftforge/forge/1.20.1-47.2.0/forge-1.20.1-47.2.0-client.jar", "url": "", "sha1": "def", "size": 3}}},
            {"name": "com.example:plain:1.0"}
        ]}))
        .unwrap();
        let p = plan(&v, &win(), &Features::none(), HOST).unwrap();
        assert_eq!(p.classpath.len(), 3);
        let urls: Vec<_> = p.downloads.iter().map(|d| d.url.as_str()).collect();
        assert_eq!(
            urls,
            vec![
                "https://libraries.minecraft.net/com/example/plain/1.0/plain-1.0.jar",
                "https://maven.fabricmc.net/net/fabricmc/fabric-loader/0.17.2/fabric-loader-0.17.2.jar",
            ]
        );
        assert_eq!(p.downloads[1].sha1.as_deref(), Some("abc"));
    }

    #[test]
    fn refuses_unsafe_paths() {
        let v: VersionJson = serde_json::from_value(json!({"id": "x", "libraries": [
            {"name": "a:b:1", "downloads": {"artifact": {"path": "../../evil.jar", "url": "https://libraries.minecraft.net/e", "sha1": "1"}}}
        ]}))
        .unwrap();
        assert!(plan(&v, &win(), &Features::none(), HOST).is_err());
    }
}
