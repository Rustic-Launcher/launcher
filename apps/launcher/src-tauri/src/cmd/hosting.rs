#[derive(Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum VpsAuth {
    Key {
        key_path: String,
        #[serde(default)]
        passphrase: Option<String>,
    },
    Password {
        password: String,
    },
}

#[derive(Deserialize)]
pub struct VpsConnectionRequest {
    pub host: String,
    pub port: u16,
    pub username: String,
    pub auth: VpsAuth,
    /// `hosting_vps_trust` only.
    #[serde(default)]
    pub fingerprint_sha256: Option<String>,
    #[serde(default)]
    pub label: Option<String>,
}

#[derive(Serialize)]
pub struct Fingerprint {
    pub algorithm: String,
    pub sha256: String,
}

#[derive(Serialize)]
pub struct VpsTestResult {
    pub reachable: bool,
    pub latency_ms: Option<u64>,
    pub fingerprint: Option<Fingerprint>,
    pub known: bool,
    pub auth_ok: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

#[derive(Serialize)]
