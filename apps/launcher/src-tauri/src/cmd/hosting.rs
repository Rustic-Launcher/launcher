/// A key generated by `hosting_vps_generate_key` lives in the keychain until a connection is
/// saved; the UI only holds this reference (`key_path`), never the key.
const KEYCHAIN_REF: &str = "keychain:";

fn pending_key_name(reference: &str) -> Option<String> {
    reference
        .strip_prefix(KEYCHAIN_REF)
        .filter(|id| rusticmc_hosting::shell::validate_name(id).is_ok())
        .map(rusticmc_hosting::secret::names::private_key)
}

fn target(req: &VpsConnectionRequest) -> SshTarget {
    SshTarget {
        host: req.host.trim().to_owned(),
        port: if req.port == 0 { 22 } else { req.port },
        user: req.username.trim().to_owned(),
    }
}

fn ssh_auth(state: &AppState, req: &VpsConnectionRequest) -> Res<SshAuth> {
    Ok(match &req.auth {
        VpsAuth::Password { password } => {
            SshAuth::Password(rusticmc_hosting::Secret::new(password.clone()))
        }
        VpsAuth::Key {
            key_path,
            passphrase,
        } => SshAuth::Key {
            private_key: match pending_key_name(key_path) {
                Some(name) => state
                    .hosting_secrets
                    .get(&name)
                    .map_err(hosting_err)?
                    .ok_or_else(|| {
                        IpcError::not_found("the generated key is no longer in the keychain")
                    })?,
                None => rusticmc_hosting::Secret::new(
                    std::fs::read_to_string(key_path)
                        .map_err(|e| IpcError::invalid(format!("{key_path}: {e}")))?,
                ),
            },
            passphrase: passphrase
                .clone()
                .filter(|p| !p.is_empty())
                .map(rusticmc_hosting::Secret::new),
        },
    })
}

/// The VPS provider of a connection profile (one SSH connection each, reused).
pub fn remote(state: &AppState, profile: &str) -> Res<Arc<dyn rusticmc_hosting::HostingProvider>> {
    Ok(remote_cached(state, profile)?)
}

/// The cached concrete provider (install options are set on it).
fn remote_cached(state: &AppState, profile: &str) -> Res<Arc<RemoteSshProvider>> {
    if let Some(p) = state.remotes.lock().expect("remotes").get(profile) {
        return Ok(p.clone());
    }
    let prof = state
        .registry
        .profile(profile)
        .ok_or_else(|| IpcError::not_found(format!("no VPS connection {profile}")))?;
    let provider = Arc::new(
        RemoteSshProvider::new(
            prof,
            state.hosting_secrets.clone(),
            state.known_hosts.clone(),
        )
        .map_err(hosting_err)?,
    );
    state
        .remotes
        .lock()
        .expect("remotes")
        .insert(profile.to_owned(), provider.clone());
    Ok(provider)
}

fn remote_ssh(state: &AppState, profile: &str) -> Res<Arc<RemoteSshProvider>> {
    let prof = state
        .registry
        .profile(profile)
        .ok_or_else(|| IpcError::not_found(format!("no VPS connection {profile}")))?;
    Ok(Arc::new(
        RemoteSshProvider::new(
            prof,
            state.hosting_secrets.clone(),
            state.known_hosts.clone(),
        )
        .map_err(hosting_err)?,
    ))
}

/// Connects once: the host key (pinned or not), whether the credentials work.
#[tauri::command]
pub async fn hosting_vps_test(state: State<'_>, args: VpsConnectionRequest) -> Res<VpsTestResult> {
    let target = target(&args);
    let auth = ssh_auth(&state, &args)?;
    let started = std::time::Instant::now();
    let r = rusticmc_hosting::ssh::SshSession::connect(
        &target,
        &auth,
        state.known_hosts.clone(),
        &rusticmc_hosting::ssh::ConnectOptions::default(),
    )
    .await;
    let latency = Some(started.elapsed().as_millis() as u64);
    let pinned = state.known_hosts.get(&target.host_id());
    Ok(match r {
        Ok(session) => {
            session.close().await;
            VpsTestResult {
                reachable: true,
                latency_ms: latency,
                fingerprint: pinned.map(|p| Fingerprint {
                    algorithm: p.algorithm,
                    sha256: p.fingerprint,
                }),
                known: true,
                auth_ok: true,
                error: None,
            }
        }
        Err(HostingError::HostKeyUnknown {
            algorithm,
            fingerprint,
            ..
        }) => VpsTestResult {
            reachable: true,
            latency_ms: latency,
            fingerprint: Some(Fingerprint {
                algorithm,
                sha256: fingerprint,
            }),
            known: false,
            auth_ok: false,
            error: None,
        },
        Err(HostingError::AuthFailed { detail, .. }) => VpsTestResult {
            reachable: true,
            latency_ms: latency,
            fingerprint: pinned.map(|p| Fingerprint {
                algorithm: p.algorithm,
                sha256: p.fingerprint,
            }),
            known: true,
            auth_ok: false,
            error: Some(detail),
        },
        Err(e @ HostingError::HostKeyMismatch { .. }) => return Err(hosting_err(e)),
        Err(e) => VpsTestResult {
            reachable: false,
            latency_ms: None,
            fingerprint: None,
            known: false,
            auth_ok: false,
            error: Some(e.to_string()),
        },
    })
}

fn profile_id(label: &str) -> String {
    let mut id = rusticmc_launcher_core::fsutil::slug(label);
    if !id.starts_with(|c: char| c.is_ascii_lowercase()) {
        id = format!("vps-{id}");
    }
    id.truncate(32);
    id.trim_end_matches('-').to_owned()
}

/// Pins the confirmed host key and saves the connection: a password is used once to install a
/// launcher-generated key (never stored); a key file stays where it is (its passphrase goes to the
/// keychain).
#[tauri::command]
pub async fn hosting_vps_trust(state: State<'_>, args: VpsConnectionRequest) -> Res<VpsConnection> {
    let target = target(&args);
    let fingerprint = args
        .fingerprint_sha256
        .clone()
        .ok_or_else(|| IpcError::invalid("fingerprint_sha256 is required"))?;
    let algorithm = match rusticmc_hosting::ssh::SshSession::connect(
        &target,
        &ssh_auth(&state, &args)?,
        state.known_hosts.clone(),
        &rusticmc_hosting::ssh::ConnectOptions::default(),
    )
    .await
    {
        Err(HostingError::HostKeyUnknown {
            algorithm,
            fingerprint: presented,
            ..
        }) => {
            if presented != fingerprint {
                return Err(IpcError::conflict(
                    "The server presented another key than the one you confirmed.",
                ));
            }
            algorithm
        }
        Ok(s) => {
            s.close().await;
            state
                .known_hosts
                .get(&target.host_id())
                .map(|p| p.algorithm)
                .unwrap_or_default()
        }
        Err(e) => return Err(hosting_err(e)),
    };
    state
        .known_hosts
        .trust(
            &target.host_id(),
            &HostKey {
                algorithm,
                fingerprint: fingerprint.clone(),
            },
        )
        .map_err(hosting_err)?;
    let label = args
        .label
        .clone()
        .unwrap_or_else(|| format!("{}@{}", target.user, target.host));
    let mut id = profile_id(&label);
    let base = id.clone();
    let mut n = 2;
    while state.registry.profile(&id).is_some() {
        id = format!("{base}-{n}");
        n += 1;
    }
    let profile = match &args.auth {
        VpsAuth::Password { password } => {
            let (p, _public) = rusticmc_hosting::remote::bootstrap_key(
                &id,
                &label,
                &target,
                &rusticmc_hosting::Secret::new(password.clone()),
                state.known_hosts.clone(),
                state.hosting_secrets.as_ref(),
                &rusticmc_hosting::ssh::ConnectOptions::default(),
            )
            .await
            .map_err(hosting_err)?;
            p
        }
        VpsAuth::Key {
            key_path,
            passphrase,
        } if pending_key_name(key_path).is_some() => {
            // A launcher-generated key: move it from its pending keychain entry to the profile's.
            let pending = pending_key_name(key_path).expect("checked");
            let key = state
                .hosting_secrets
                .get(&pending)
                .map_err(hosting_err)?
                .ok_or_else(|| {
                    IpcError::not_found("the generated key is no longer in the keychain")
                })?;
            state
                .hosting_secrets
                .set(&rusticmc_hosting::secret::names::private_key(&id), &key)
                .map_err(hosting_err)?;
            if pending != rusticmc_hosting::secret::names::private_key(&id) {
                let _ = state.hosting_secrets.delete(&pending);
            }
            if let Some(pass) = passphrase.as_ref().filter(|p| !p.is_empty()) {
                state
                    .hosting_secrets
                    .set(
                        &rusticmc_hosting::secret::names::passphrase(&id),
                        &rusticmc_hosting::Secret::new(pass.clone()),
                    )
                    .map_err(hosting_err)?;
            }
            RemoteProfile {
                id: id.clone(),
                label: label.clone(),
                target: target.clone(),
                auth: AuthMethod::KeychainKey,
            }
        }
        VpsAuth::Key {
            key_path,
            passphrase,
        } => {
            if let Some(pass) = passphrase.as_ref().filter(|p| !p.is_empty()) {
                state
                    .hosting_secrets
                    .set(
                        &rusticmc_hosting::secret::names::passphrase(&id),
                        &rusticmc_hosting::Secret::new(pass.clone()),
                    )
                    .map_err(hosting_err)?;
            }
            RemoteProfile {
                id: id.clone(),
                label: label.clone(),
                target: target.clone(),
                auth: AuthMethod::KeyFile {
                    path: PathBuf::from(key_path),
                },
            }
        }
    };
    state
        .registry
        .upsert_profile(profile.clone())
        .map_err(hosting_err)?;
    Ok(connection_dto(&state, &profile))
}

fn connection_dto(state: &AppState, p: &RemoteProfile) -> VpsConnection {
    let pin = state.known_hosts.get(&p.target.host_id());
    VpsConnection {
        id: p.id.clone(),
        label: p.label.clone(),
        host: p.target.host.clone(),
        port: p.target.port,
        username: p.target.user.clone(),
        fingerprint_sha256: pin
            .as_ref()
            .map(|p| p.fingerprint.clone())
            .unwrap_or_default(),
        added_at: iso(pin.map_or(0, |p| p.pinned_at)),
    }
}

#[tauri::command]
pub fn hosting_vps_list(state: State<'_>) -> Vec<VpsConnection> {
    state
        .registry
        .snapshot()
        .profiles
        .iter()
        .map(|p| connection_dto(&state, p))
        .collect()
}

#[tauri::command]
pub async fn hosting_vps_remove(state: State<'_>, args: IdArgs) -> Res<()> {
    if let Some(p) = state.remotes.lock().expect("remotes").remove(&args.id) {
        drop(p);
    }
    let _ = state
        .hosting_secrets
        .delete(&rusticmc_hosting::secret::names::private_key(&args.id));
    let _ = state
        .hosting_secrets
        .delete(&rusticmc_hosting::secret::names::passphrase(&args.id));
    state.registry.remove_profile(&args.id).map_err(hosting_err)
}

#[tauri::command]
pub async fn hosting_vps_check(state: State<'_>, args: ConnectionIdArgs) -> Res<VpsResources> {
    let p = remote_ssh(&state, &args.connection_id)?;
    let info = p.test_connection().await.map_err(hosting_err)?;
    p.disconnect().await;
    let memory_mb = info.mem_total_kb / 1024;
    let disk_free_mb = info
        .disk_home_available_kb
        .max(info.disk_varlib_available_kb)
        / 1024;
    let mut problems = Vec::new();
    if memory_mb < 1536 {
        problems.push(VpsProblem {
            code: "memory",
            detail: format!("{memory_mb} MB of memory; 2 GB or more is recommended"),
        });
    }
    if disk_free_mb < 3072 {
        problems.push(VpsProblem {
            code: "disk",
            detail: format!("{disk_free_mb} MB free; 3 GB or more is needed"),
        });
    }
    if !info.systemd {
        problems.push(VpsProblem {
            code: "systemd",
            detail: "no systemd: the server can't run as a service".into(),
        });
    }
    Ok(VpsResources {
        os: info.os.pretty_name.clone(),
        arch: info.arch.as_str().into(),
        cpu_cores: info.cpus,
        memory_mb,
        disk_free_mb,
        has_systemd: info.systemd,
        public_ip: state
            .registry
            .profile(&args.connection_id)
            .map(|p| p.target.host),
        requirements_met: problems.is_empty(),
        problems,
    })
}

/// A launcher-generated Ed25519 key for a VPS (SECURITY "Remote hosting"): the private key goes to
/// the OS keychain under a pending entry, never to a file; the UI gets a `keychain:<id>` reference
/// (as `key_path`) and the public line with the one command that authorises it on the VPS.
#[tauri::command]
pub fn hosting_vps_generate_key(state: State<'_>, args: LabelArgs) -> Res<GeneratedSshKey> {
    let comment = format!("rustic-launcher-{}", profile_id(&args.label));
    let key = rusticmc_hosting::ssh::generate_key(&comment).map_err(hosting_err)?;
    let digest: String = key
        .fingerprint
        .trim_start_matches("SHA256:")
        .chars()
        .filter(char::is_ascii_alphanumeric)
        .take(16)
        .collect();
    let pending = format!("pending-{}", digest.to_ascii_lowercase());
    state
        .hosting_secrets
        .set(
            &rusticmc_hosting::secret::names::private_key(&pending),
            &key.private_openssh,
        )
        .map_err(hosting_err)?;
    Ok(GeneratedSshKey {
        key_path: format!("{KEYCHAIN_REF}{pending}"),
        authorize_command: rusticmc_hosting::ssh::authorize_key_script(&key.public_line)
            .map_err(hosting_err)?,
        public_key: key.public_line,
    })
}

/// Installs a server on a VPS as a background task; progress goes out as `hosting-install`.
pub async fn install_on_vps(
    state: &Arc<AppState>,
    connection_id: String,
    req: CreateServerRequest,
    open_firewall: bool,
) -> Res<CreateServerResult> {
    let provider = remote_cached(state, &connection_id)?;
    let mut name = rusticmc_launcher_core::fsutil::slug(&req.name);
    if !name.starts_with(|c: char| c.is_ascii_lowercase()) {
        name = format!("s-{name}");
    }
    name.truncate(32);
    let spec = spec_for(state, &req, &name)?;
    let options = rusticmc_hosting::RemoteInstallOptions {
        open_firewall,
        ..Default::default()
    };
    let meta = ServerMeta {
        profile: connection_id.clone(),
        name: name.clone(),
        display_name: req.name.clone(),
        icon: req.icon.clone(),
        rustic: req.engine == "rustic",
        horizon_version: req.horizon_version.clone(),
        port: spec.port,
        world: spec.world.clone(),
        max_players: req.max_players,
        memory_mb: req.memory_mb,
        created_at: time::now(),
    };
    state.add_server_meta(meta);
    let id = remote_id(&connection_id, &name);
    let (task, _) = state.tasks.start(
        "server",
        format!("Install {} on the VPS", req.name),
        None,
        Some(id.clone()),
    );
    let st = state.clone();
    let task2 = task.clone();
    let id2 = id.clone();
    tauri::async_runtime::spawn(async move {
        let steps = std::sync::Mutex::new(Vec::<serde_json::Value>::new());
        let sink = |e: ProgressEvent| {
            let ui = rusticmc_hosting::model::ui_step(&e.step);
            let state_name = match e.state {
                StepState::Running | StepState::RollingBack | StepState::Warning => "running",
                StepState::Done => "done",
                StepState::Skipped => "skipped",
                StepState::Failed | StepState::RolledBack => "failed",
            };
            let mut list = steps.lock().expect("steps");
            match list.iter_mut().find(|s| s["id"] == ui) {
                // A warning keeps the step's state and only adds its text.
                Some(s) if e.state == StepState::Warning => {
                    s["detail"] = e.detail.clone().into();
                }
                Some(s) => {
                    s["state"] = state_name.into();
                    if e.detail.is_some() || e.state != StepState::Running {
                        s["detail"] = e.detail.clone().into();
                    }
                }
                None => list
                    .push(serde_json::json!({ "id": ui, "state": state_name, "detail": e.detail })),
            }
            st.tasks
                .fraction(&task2, (e.index as f64 + 1.0) / (e.total.max(1) as f64));
            let _ = st.app.emit(
                "hosting-install",
                serde_json::json!({
                    "task_id": task2, "server_id": id2, "steps": *list,
                    "log": match &e.detail {
                        Some(d) => format!("{}: {d}", e.title),
                        None => e.title.clone(),
                    },
                    "done": false
                }),
            );
        };
        let result = provider.install_with(&spec, options, &sink).await;
        let (done_steps, error) = {
            let list = steps.lock().expect("steps").clone();
            (list, result.as_ref().err().map(|e| e.to_string()))
        };
        let _ = st.app.emit("hosting-install", serde_json::json!({
            "task_id": task2, "server_id": id2, "steps": done_steps, "done": true, "error": error
        }));
        match result {
            Ok(server_ref) => {
                let _ = st.registry.add_server(server_ref);
                st.tasks.finish(&task2);
            }
            Err(e) => st.tasks.fail(&task2, e.to_string()),
        }
        servers_changed(&st).await;
    });
    let server = server_dto(state, &id).await?;
    Ok(CreateServerResult {
        server,
        task_id: task,
    })
}

#[tauri::command]
pub async fn hosting_vps_install(
    state: State<'_>,
    args: VpsInstallRequest,
) -> Res<CreateServerResult> {
    if !args.server.eula_accepted {
        return Err(IpcError::new(
            IpcErrorCode::InvalidArgument,
            "Accept the Minecraft EULA to create a server.",
        ));
    }
    install_on_vps(&state, args.connection_id, args.server, args.open_firewall).await
}
